-- 대상: Oracle Database XE (18c/21c 기준, IDENTITY 컬럼 사용)
-- 실행 방법: SQL*Plus / SQL Developer 등에서 scott 계정으로 접속 후 1회 수동 실행
--           (스프링 부트가 자동으로 실행하지 않음 - 재시작마다 재실행되어
--            기존 데이터와 충돌하는 것을 막기 위해 의도적으로 자동 실행 대상에서 제외함)
